def build():
    out = {"en": [], "de": []}
    def add(name, en, de):
        out["en"].append((name, en)); out["de"].append((name, de))
    for k, (en, de) in S.items(): add(k, en, de)
    for k, (en, de) in CAT.items(): add("cat_" + k, en, de)
    for k, (en, de) in UNITS.items(): add("unit_" + k, en, de)
    for k, (en, de) in STYLE.items(): add("style_" + k, en, de)
    for k, (en, de) in FLAVOR.items(): add("flavor_" + k, en, de)
    for k, (en, de) in SPIRITS.items(): add("spirit_" + k, en, de)
    base = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")
    for lang, folder in (("en", "values"), ("de", "values-de")):
        os.makedirs(os.path.join(base, folder), exist_ok=True)
        with open(os.path.join(base, folder, "strings.xml"), "w", encoding="utf-8") as f:
            f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n')
            for name, val in out[lang]:
                v = escape(val).replace("'", "\\'").replace('"', '\\"')
                attr = ' formatted="false"' if "%%" not in val and "%" in val and "$" not in val else ""
                f.write(f'    <string name="{name}"{attr}>{v}</string>\n')
            f.write("</resources>\n")
    # Kotlin lookup tables for dynamic keys
    kt = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "java", "de", "schnubbirunkel", "barkeep", "ui", "Labels.kt")
    with open(kt, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_strings.py – do not edit.\npackage de.schnubbirunkel.barkeep.ui\n\nimport de.schnubbirunkel.barkeep.R\n\nobject Labels {\n")
        occ = {k[len("occasion_"):]: v for k, v in S.items() if k.startswith("occasion_")}
        for prefix, table in (("cat", CAT), ("unit", UNITS), ("style", STYLE), ("flavor", FLAVOR), ("spirit", SPIRITS), ("occasion", occ)):
            f.write(f"    val {prefix}: Map<String, Int> = mapOf(\n")
            for k in table:
                f.write(f'        "{k}" to R.string.{prefix}_{k},\n')
            f.write("    )\n")
        f.write("}\n")
    print(len(out["en"]), "strings")


if __name__ == "__main__":
    build()
